					local dist = dbase[ds + 1] + getbits(dext[ds + 1])
					for _ = 1, len do o = o + 1; out[o] = out[o - dist] end
				end
			end
		end
	until last == 1
	local parts = {}
	for i = 1, o, 4000 do
		parts[#parts + 1] = char(table.unpack(out, i, math.min(i + 3999, o)))
	end
	return table.concat(parts)
end
