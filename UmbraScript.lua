	local order = {16,17,18,0,8,7,9,6,10,5,11,4,12,3,13,2,14,1,15}
	local out, o = {}, 0
	repeat
		local last = getbits(1)
		local typ = getbits(2)
		if typ == 0 then
			buf, cnt = 0, 0
			local len = s[pos] + s[pos + 1] * 256
			pos = pos + 4
			for _ = 1, len do o = o + 1; out[o] = s[pos]; pos = pos + 1 end
		else
			local lh, dh
			if typ == 1 then
				local l = {}
				for i = 0, 143 do l[i] = 8 end
				for i = 144, 255 do l[i] = 9 end
				for i = 256, 279 do l[i] = 7 end
				for i = 280, 287 do l[i] = 8 end
				lh = build(l, 288)
				local d = {}
				for i = 0, 29 do d[i] = 5 end
				dh = build(d, 30)
			else
				local nlen, ndist, ncode = getbits(5) + 257, getbits(5) + 1, getbits(4) + 4
				local l = {}
				for i = 0, 18 do l[i] = 0 end
				for i = 1, ncode do l[order[i]] = getbits(3) end
				local ch = build(l, 19)
				local lens, i = {}, 0
				while i < nlen + ndist do
					local sym = decode(ch)
					if sym < 16 then
						lens[i] = sym; i = i + 1
					else
						local prev, rep = 0, 0
						if sym == 16 then prev = lens[i - 1]; rep = 3 + getbits(2)
						elseif sym == 17 then rep = 3 + getbits(3)
						else rep = 11 + getbits(7) end
						for _ = 1, rep do lens[i] = prev; i = i + 1 end
					end
				end
				local ll, dd = {}, {}
				for k = 0, nlen - 1 do ll[k] = lens[k] end
				for k = 0, ndist - 1 do dd[k] = lens[nlen + k] end
				lh = build(ll, nlen)
				dh = build(dd, ndist)
			end
			while true do
				local sym = decode(lh)
				if sym < 256 then
					o = o + 1; out[o] = sym
				elseif sym == 256 then
					break
				else
					sym = sym - 257
					local len = lbase[sym + 1] + getbits(lext[sym + 1])
