		local count, symbol, offs = {}, {}, {}
		for i = 0, 15 do count[i] = 0 end
		for i = 0, n - 1 do count[lengths[i]] = count[lengths[i]] + 1 end
		offs[1] = 0
		for i = 1, 14 do offs[i + 1] = offs[i] + count[i] end
