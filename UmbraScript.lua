local B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local byte, floor, char = string.byte, math.floor, string.char
local function unpack64(data)
	local map = {}
	for i = 1, 64 do map[byte(B64, i)] = i - 1 end
	local t, n, acc, bc = {}, 0, 0, 0
	for i = 1, #data do
		local v = map[byte(data, i)]
		if v then
			acc = acc * 64 + v
			bc = bc + 6
			if bc >= 8 then
				bc = bc - 8
				local d = 2 ^ bc
				n = n + 1
				t[n] = floor(acc / d)
				acc = acc % d
			end
		end
	end
	return t
end
local function inflate(s)
	local pos, buf, cnt = 1, 0, 0
	local function getbits(n)
		while cnt < n do
			buf = buf + (s[pos] or 0) * 2 ^ cnt
			pos = pos + 1
			cnt = cnt + 8
		end
		local p = 2 ^ n
		local v = buf % p
		buf = floor(buf / p)
		cnt = cnt - n
		return v
	end
	local function build(lengths, n)
		local count, symbol, offs = {}, {}, {}
		for i = 0, 15 do count[i] = 0 end
		for i = 0, n - 1 do count[lengths[i]] = count[lengths[i]] + 1 end
		offs[1] = 0
		for i = 1, 14 do offs[i + 1] = offs[i] + count[i] end
		for i = 0, n - 1 do
			local l = lengths[i]
			if l ~= 0 then symbol[offs[l]] = i; offs[l] = offs[l] + 1 end
		end
		return { count = count, symbol = symbol }
	end
	local function decode(h)
		local code, first, index = 0, 0, 0
		for len = 1, 15 do
			code = code + getbits(1)
			local c = h.count[len]
			if code - c < first then return h.symbol[index + (code - first)] end
			index = index + c
			first = (first + c) * 2
			code = code * 2
		end
		error("bad code")
	end
	local lbase = {3,4,5,6,7,8,9,10,11,13,15,17,19,23,27,31,35,43,51,59,67,83,99,115,131,163,195,227,258}
