local B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local byte, floor, char = string.byte, math.floor, string.char
local function unpack64(data)
	local map = {}
	for i = 1, 64 do map[byte(B64, i)] = i - 1 end
	local t, n, acc, bc = {}, 0, 0, 0
	for i = 1, #data do
		local v = map[byte(data, i)]
		if v then
			acc = acc * 64 + v
			bc = bc + 6
			if bc >= 8 then
				bc = bc - 8
				local d = 2 ^ bc
				n = n + 1
				t[n] = floor(acc / d)
				acc = acc % d
			end
		end
	end
	return t
end
