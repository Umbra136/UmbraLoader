				for k = 0, nlen - 1 do ll[k] = lens[k] end
				for k = 0, ndist - 1 do dd[k] = lens[nlen + k] end
				lh = build(ll, nlen)
				dh = build(dd, ndist)
			end
			while true do
				local sym = decode(lh)
				if sym < 256 then
					o = o + 1; out[o] = sym
				elseif sym == 256 then
					break
				else
					sym = sym - 257
					local len = lbase[sym + 1] + getbits(lext[sym + 1])
